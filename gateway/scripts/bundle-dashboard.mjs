import { readFile } from "node:fs/promises";

// Reproducible, dependency-free delivery for Cloudflare's single-file Dashboard editor.
// This is deliberately limited to these modules, rather than a general JavaScript bundler.
const modules = ["cloudkit-request.mjs", "cloudkit-probe.mjs", "probe-http.mjs", "probe-gate.mjs", "runtime-check.mjs", "worker.mjs"];
const imports = new Set([
  'import { Buffer } from "node:buffer";',
  'import { createHash, createPrivateKey, sign } from "node:crypto";',
  'import { randomUUID } from "node:crypto";',
  'import { createHash, timingSafeEqual } from "node:crypto";',
  'import { makeDevelopmentProbeContext } from "./cloudkit-probe.mjs";',
  'import { jsonResponse } from "./probe-http.mjs";',
  'import { DurableObject } from "cloudflare:workers";',
  'import { CloudKitDevelopmentSigner } from "./cloudkit-request.mjs";',
  'import { probeCloudKitDevelopment } from "./cloudkit-probe.mjs";',
  'import { activeProbeConfiguration, handleDevelopmentProbe, jsonResponse } from "./probe-http.mjs";',
  'import { runReservedProbe } from "./probe-gate.mjs";',
  'import { inspectDevelopmentRuntime } from "./runtime-check.mjs";',
]);
const output = [
  "// Generated by gateway/scripts/bundle-dashboard.mjs. Edit the source modules, not this bundle.",
  'import { Buffer } from "node:buffer";',
  'import { createHash, createPrivateKey, sign, randomUUID, timingSafeEqual } from "node:crypto";',
  'import { DurableObject } from "cloudflare:workers";',
];
for (const name of modules) {
  const source = await readFile(new URL(`../src/${name}`, import.meta.url), "utf8");
  const lines = source.split("\n").filter((line) => {
    if (!line.startsWith("import ")) return true;
    if (!imports.has(line)) throw new Error(`Unrecognized import in ${name}; review the bundler.`);
    return false;
  });
  let body = lines.join("\n");
  if (name !== "worker.mjs") body = body.replace(/^export (?=(?:async )?(?:function|class) )/gm, "");
  output.push(`\n// Source: ${name}\n${body}`);
}
process.stdout.write(output.join("\n"));
